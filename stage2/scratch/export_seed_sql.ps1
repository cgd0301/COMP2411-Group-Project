# Generates sql/02_data.sql from the sql columns of stage2/notes/seed_plan.xlsx (opened read-only).
# Run it again after every change to the workbook data; never edit 02_data.sql by hand.
# Run order after a full rebuild: build_seed_plan.ps1 -> extend_seed_plan.ps1 -> export_seed_sql.ps1
#   powershell -ExecutionPolicy Bypass -File stage2\scratch\export_seed_sql.ps1

$ErrorActionPreference = 'Stop'

$book = (Resolve-Path (Join-Path $PSScriptRoot '..\notes\seed_plan.xlsx')).Path
$out  = Join-Path $PSScriptRoot '..\COMP2411_2026_G085_Stage2\sql\02_data.sql'
$lock = Join-Path (Split-Path $book) '~$seed_plan.xlsx'
if (Test-Path $lock) { throw "seed_plan.xlsx is open in Excel. Save and close it, then run again." }

function Get-Values($lo, [string]$col) {
    $v = $lo.ListColumns.Item($col).DataBodyRange.Value2
    $list = New-Object System.Collections.Generic.List[object]
    for ($i = 1; $i -le $v.GetLength(0); $i++) {
        $x = $v[$i, 1]
        $list.Add($x)
    }
    return , $list
}

function Get-Sql($lo) {
    $vals = Get-Values $lo 'sql'
    for ($i = 0; $i -lt $vals.Count; $i++) {
        if (-not ($vals[$i] -is [string]) -or -not $vals[$i].StartsWith('(')) {
            throw "$($lo.Name) row $($i + 1): the sql cell does not hold a tuple (Excel error or empty)."
        }
    }
    return , $vals
}

# rows: list of @{ tuple; comment; group } ; group lines are written as a comment before the row
function Add-Section($lines, [string]$comment, [string]$insert, $rows) {
    $lines.Add($comment)
    $lines.Add($insert)
    $width = 0
    foreach ($r in $rows) { if ($r.tuple.Length -gt $width) { $width = $r.tuple.Length } }
    for ($i = 0; $i -lt $rows.Count; $i++) {
        $r = $rows[$i]
        if ($r.group) { $lines.Add('    -- ' + $r.group) }
        $sep = $(if ($i -eq $rows.Count - 1) { ';' } else { ',' })
        $line = '    ' + $r.tuple + $sep
        if ($r.comment) { $line = $line.PadRight($width + 7) + '-- ' + $r.comment }
        $lines.Add($line.TrimEnd())
    }
    $lines.Add('')
}

$xl = $null; $wb = $null
try {
    $xl = New-Object -ComObject Excel.Application
    $xl.Visible = $false
    $xl.DisplayAlerts = $false
    $wb = $xl.Workbooks.Open($book, 0, $true)
    $xl.CalculateFull()

    $lo = @{}
    foreach ($p in @(@('season', 't_season'), @('product', 't_product'), @('customer', 't_customer'),
                     @('subscription', 't_sub'), @('chosen', 't_chosen'), @('delivery', 't_delivery'),
                     @('add_on', 't_add_on'), @('refund', 't_refund'))) {
        $lo[$p[1]] = $wb.Worksheets.Item($p[0]).ListObjects.Item($p[1])
    }

    $seasonLabel = @{}
    $sid = Get-Values $lo['t_season'] 'season_id'; $slab = Get-Values $lo['t_season'] 'label'
    for ($i = 0; $i -lt $sid.Count; $i++) { $seasonLabel[[int]$sid[$i]] = [string]$slab[$i] }

    $subNote = @{}
    $subId = Get-Values $lo['t_sub'] 'subscription_id'; $subN = Get-Values $lo['t_sub'] 'note'
    for ($i = 0; $i -lt $subId.Count; $i++) { $subNote[[int]$subId[$i]] = [string]$subN[$i] }

    $lines = New-Object System.Collections.Generic.List[string]
    $lines.Add('-- File:          sql/02_data.sql')
    $lines.Add('-- Purpose:       Synthetic seed data: the state of Farmlander Farm at the start of')
    $lines.Add('--                Tuesday 2026-07-07, before any operation of that day.')
    $lines.Add('-- Related IDs:   BR1-BR11')
    $lines.Add('-- Prerequisites: sql/01_schema.sql has just been run on an empty database that is')
    $lines.Add('--                selected as the current database.')
    $lines.Add('-- Note:          Generated from the seed workbook of the team. Do not edit this file')
    $lines.Add('--                by hand: change the workbook and generate the file again.')
    $lines.Add('--                Rows: season 4, product 40, customer 15, subscription 25,')
    $lines.Add('--                chosen_products 64, delivery 198, add_on 11, refund 15.')
    $lines.Add('')

    # season
    $rows = @(); $t = Get-Sql $lo['t_season']
    foreach ($s in $t) { $rows += @{ tuple = $s } }
    Add-Section $lines '-- Seasons (BR3). first_planning_day is the Monday D of week 1; the range runs from D-6 to D+77.' `
        'INSERT INTO season (season_id, season_name, year, first_planning_day) VALUES' $rows

    # product
    $rows = @(); $t = Get-Sql $lo['t_product']; $ps = Get-Values $lo['t_product'] 'season_id'
    $prev = -1
    for ($i = 0; $i -lt $t.Count; $i++) {
        $g = $null
        if ([int]$ps[$i] -ne $prev) { $prev = [int]$ps[$i]; $g = $seasonLabel[$prev] }
        $rows += @{ tuple = $t[$i]; group = $g }
    }
    Add-Section $lines '-- Products (BR6, BR9): 10 per season, 6 of them with is_farmers_choice = 1.' `
        'INSERT INTO product (product_id, season_id, name, is_farmers_choice, price_per_kg) VALUES' $rows

    # customer
    $rows = @(); $t = Get-Sql $lo['t_customer']; $cast = Get-Values $lo['t_customer'] 'cast_id'
    for ($i = 0; $i -lt $t.Count; $i++) { $rows += @{ tuple = $t[$i]; comment = [string]$cast[$i] } }
    Add-Section $lines '-- Customers (BR1): fictional people; C13 and C14 have no subscription.' `
        'INSERT INTO customer (customer_id, name, email, street, building, room) VALUES' $rows

    # subscription
    $rows = @(); $t = Get-Sql $lo['t_sub']
    for ($i = 0; $i -lt $t.Count; $i++) { $rows += @{ tuple = $t[$i]; comment = $subNote[[int]$subId[$i]] } }
    Add-Section $lines '-- Subscriptions (BR1-BR5, BR8, BR10): status as on 2026-07-07; renewal prices follow BR4 and BR5.' `
        'INSERT INTO subscription (subscription_id, customer_id, season_id, status, plan_type, frequency, allocated_cost, submission_date, cancellation_date, remaining_refundable_skip) VALUES' $rows

    # chosen_products
    $rows = @(); $t = Get-Sql $lo['t_chosen']; $cs = Get-Values $lo['t_chosen'] 'subscription_id'; $cn = Get-Values $lo['t_chosen'] 'product_name'
    $prev = -1
    for ($i = 0; $i -lt $t.Count; $i++) {
        $g = $null
        if ([int]$cs[$i] -ne $prev) { $prev = [int]$cs[$i]; $g = "subscription $prev ($($subNote[$prev].Split(':')[0]))" }
        $rows += @{ tuple = $t[$i]; comment = [string]$cn[$i]; group = $g }
    }
    Add-Section $lines '-- Chosen products (BR6): exactly 8 of the 10 products of its season for each customizable subscription.' `
        'INSERT INTO chosen_products (subscription_id, product_id) VALUES' $rows

    # delivery
    $rows = @(); $t = Get-Sql $lo['t_delivery']; $ds = Get-Values $lo['t_delivery'] 'subscription_id'
    $prev = -1
    for ($i = 0; $i -lt $t.Count; $i++) {
        $g = $null
        if ([int]$ds[$i] -ne $prev) { $prev = [int]$ds[$i]; $g = "subscription ${prev}: $($subNote[$prev])" }
        $rows += @{ tuple = $t[$i]; group = $g }
    }
    Add-Section $lines '-- Deliveries (BR7, BR8, BR10): weekly weeks 1-12, biweekly odd weeks; status as on 2026-07-07.' `
        'INSERT INTO delivery (subscription_id, week_no, status) VALUES' $rows

    # add_on
    $rows = @(); $t = Get-Sql $lo['t_add_on']; $an = Get-Values $lo['t_add_on'] 'product_name'; $ast = Get-Values $lo['t_add_on'] 'delivery_status'
    for ($i = 0; $i -lt $t.Count; $i++) { $rows += @{ tuple = $t[$i]; comment = "$($an[$i]), delivery $($ast[$i])" } }
    Add-Section $lines '-- Add-ons (BR9): weight >= 0.10 kg, products within the plan of the subscription.' `
        'INSERT INTO add_on (subscription_id, week_no, product_id, weight) VALUES' $rows

    # refund
    $rows = @(); $t = Get-Sql $lo['t_refund']; $rn = Get-Values $lo['t_refund'] 'note'
    for ($i = 0; $i -lt $t.Count; $i++) { $rows += @{ tuple = $t[$i]; comment = [string]$rn[$i] } }
    Add-Section $lines '-- Refunds (BR7, BR8, BR10, BR11) in date order; a zero refund has no row (D20).' `
        'INSERT INTO refund (refund_id, subscription_id, amount, type, refund_date, week_no) VALUES' $rows

    while ($lines.Count -gt 0 -and $lines[$lines.Count - 1] -eq '') { $lines.RemoveAt($lines.Count - 1) }
    $text = ($lines -join "`r`n") + "`r`n"
    [IO.File]::WriteAllText([IO.Path]::GetFullPath($out), $text, (New-Object System.Text.UTF8Encoding($false)))
    Write-Output ("wrote {0} lines to {1}" -f $lines.Count, [IO.Path]::GetFullPath($out))

    $wb.Close($false)
    $wb = $null
}
finally {
    if ($wb) { $wb.Close($false) }
    if ($wb) { [void][Runtime.InteropServices.Marshal]::ReleaseComObject($wb) }
    if ($xl) { $xl.Quit(); [void][Runtime.InteropServices.Marshal]::ReleaseComObject($xl) }
    [GC]::Collect()
    [GC]::WaitForPendingFinalizers()
}
